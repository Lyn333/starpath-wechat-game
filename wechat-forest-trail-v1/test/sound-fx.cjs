const assert = require("node:assert/strict");
const createdAudio = [];
function createAudio() {
  const events = [];
  const audio = { events, set src(value) { events.push(`src:${value}`); }, set autoplay(value) { events.push(`autoplay:${value}`); }, set loop(value) { events.push(`loop:${value}`); }, set volume(value) { events.push(`volume:${value}`); }, set obeyMuteSwitch(value) { events.push(`obeyMuteSwitch:${value}`); }, stop() { events.push("stop"); }, seek(value) { events.push(`seek:${value}`); }, play() { events.push("play"); }, destroy() { events.push("destroy"); } };
  createdAudio.push(audio); return audio;
}
global.wx = { createInnerAudioContext: createAudio };
const { SoundFx } = require("../core/SoundFx");
const sound = new SoundFx(true, .7);
sound.startBackgroundMusic();
const background = createdAudio[0];
assert.equal(background.events[0], "src:audio/forest-trail-background.mp3");
assert.ok(background.events.includes("loop:true"), "背景音乐必须循环播放");
assert.ok(background.events.includes(`volume:${.28 * .7}`), "背景音乐应采用初始音量档位");
assert.equal(background.events.at(-1), "play");
sound.step(); sound.tap(); sound.undo(); sound.reset(); sound.complete();
assert.equal(createdAudio.length, 1, "普通连线和界面操作不得创建数字音效");
sound.coin();
const numberEffect = createdAudio[1];
assert.equal(numberEffect.events[0], "src:audio/forest-trail-number-effect.mp3");
assert.ok(numberEffect.events.includes("loop:false"), "数字音效不得循环");
assert.deepEqual(numberEffect.events.slice(-3), ["stop", "seek:0", "play"], "合法数字触达应从音效起点播放");
sound.setVolume(1);
assert.equal(background.events.at(-1), "volume:0.28", "最高档位应更新背景音乐音量");
assert.equal(numberEffect.events.at(-1), "volume:0.72", "最高档位应更新数字音效音量");
sound.setEnabled(false);
assert.equal(background.events.at(-1), "stop", "关闭音效应停止背景音乐");
assert.equal(numberEffect.events.at(-1), "stop", "关闭音效应停止数字音效");
const beforeMuted = createdAudio.length; sound.coin(); assert.equal(createdAudio.length, beforeMuted, "关闭音效后不得播放数字触达音乐");
sound.setEnabled(true); assert.equal(background.events.at(-1), "play", "重新开启音效应恢复背景音乐");
sound.destroy(); assert.equal(background.events.at(-1), "destroy"); assert.equal(numberEffect.events.at(-1), "destroy");
console.log("背景音乐、数字触达音乐、音量和静音开关校验通过");
